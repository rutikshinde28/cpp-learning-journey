#include<iostream>
using namespace std;
int main()
{
    int x=3;
    cout << x << endl;              //output 3
    x++;
    cout << x << endl;              //output 4
    x--;
    cout << x << endl;              //output 3
    ++x;
    cout << x << endl;              //output 4
    --x;
    cout << x << endl;              //output 3
    return 0;
}