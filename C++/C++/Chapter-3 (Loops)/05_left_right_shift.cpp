#include<iostream>
using namespace std;
int main()
{
    cout << (~2) << endl;
    cout << (8 >> 2) << endl;      //Right Shift (Division)
    cout << (8 << 2) << endl;      //Left Shift (Multiplication)
    cout << (2^3) << endl;        // using xor  (Same no give-0 and different no gives-1)
}